/*
  When returning RFC 7807 errors:
  - Header: `Content-Type: application/problem+json`
  - Never include internal stack traces or database connection strings in production!
  - Always provide a unique `instance` path or trace request ID (e.g. `req_abc123`)
    so users can quote it to customer support to look up the server log.
*/