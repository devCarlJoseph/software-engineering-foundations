// =============================================================================
// GOOD PRACTICE: RFC 7807 "PROBLEM DETAILS" IMPLEMENTATION
// =============================================================================

interface ProblemDetails {
  type: string;
  title: string;
  status: number;
  detail: string;
  instance: string;
  invalidParams?: Array<{ name: string; reason: string }>;
}

class ProblemDetailsFactory {
  // 400 Bad Request / Validation Failure
  public static validationError(
    instanceUri: string,
    invalidFields: Array<{ name: string; reason: string }>
  ): ProblemDetails {
    return {
      type: "https://api.taskflow.dev/errors/validation-error",
      title: "Your request parameters failed validation.",
      status: 400,
      detail: "One or more fields in your request payload do not satisfy constraints.",
      instance: instanceUri,
      invalidParams: invalidFields,
    };
  }

  // 404 Not Found
  public static notFoundError(instanceUri: string, resourceName: string, id: string): ProblemDetails {
    return {
      type: "https://api.taskflow.dev/errors/resource-not-found",
      title: "Resource Not Found",
      status: 404,
      detail: `The requested ${resourceName} with identifier '${id}' does not exist on this server.`,
      instance: instanceUri,
    };
  }

  // 409 Conflict
  public static conflictError(instanceUri: string, reason: string): ProblemDetails {
    return {
      type: "https://api.taskflow.dev/errors/resource-conflict",
      title: "Resource State Conflict",
      status: 409,
      detail: reason,
      instance: instanceUri,
    };
  }
}

console.log("=== RFC 7807 Error 1: Validation Failure (HTTP 400) ===");
const valError = ProblemDetailsFactory.validationError("/api/v1/tasks", [
  { name: "title", reason: "Title cannot be empty." },
  { name: "priority", reason: "Value must be low, medium, or high." },
]);
console.log(JSON.stringify(valError, null, 2));

console.log("\n=== RFC 7807 Error 2: Resource Not Found (HTTP 404) ===");
const notFound = ProblemDetailsFactory.notFoundError("/api/v1/tasks/tsk_99", "Task", "tsk_99");
console.log(JSON.stringify(notFound, null, 2));

