/*
  ==============================================================================
  W3SCHOOLS-STYLE LEARNING GUIDE: REST API Error Responses (RFC 7807 Standard)
  ==============================================================================

  1. WHAT ARE STANDARDIZED ERROR RESPONSES?
     In REST, error responses must be consistent, actionable, and machine-readable.
     RFC 7807 ("Problem Details for HTTP APIs") is the official IETF standard specification
     defining a standard JSON media type for HTTP error reporting:
     `application/problem+json`.

  2. REAL-LIFE ANALOGY:
     A Medical Diagnostic Report:
     - Bad error report: Doctor says "Something is wrong" (Vague, no code).
     - Good RFC 7807 report: Lists ICD Code (E11.9), Title ("Type 2 Diabetes"),
       Specific severity, and exact next treatment steps.

  3. JARGON BUSTER:
     - RFC 7807 Problem Details fields:
       - `type`: A URI reference that identifies the problem type documentation.
       - `title`: A short, human-readable summary of the problem type.
       - `status`: The HTTP status code generated by the origin server.
       - `detail`: A human-readable explanation specific to this occurrence.
       - `instance`: A URI reference that identifies the specific endpoint or trace ID.
       - `invalidParams`: Custom extension array listing specific field violations.
*/

